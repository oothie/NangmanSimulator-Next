'use strict';
const assert=require('node:assert/strict');
const {typedKey,normalize,resolve,compareOrders}=require('./typed-weight-roll.cjs');
assert.notEqual(typedKey(50),typedKey('50'));
assert.notEqual(typedKey(50),typedKey('50 '));
assert.notEqual(typedKey('50'),typedKey('50 '));
assert.deepEqual(normalize([{key:50,weight:50},{key:'50 ',weight:50}]).map(e=>e.keyId),['n:50','s:50 ']);
assert.throws(()=>normalize([{key:50,weight:1},{key:50,weight:2}]),/Duplicate/);
const pair=[{key:50,weight:50},{key:'50 ',weight:50}];
assert.equal(resolve(pair,null,1).status,'unresolved');
assert.throws(()=>resolve(pair,[50,'50'],1),/permutation/);
assert.equal(resolve(pair,[50,'50 '],51).selected.key,'50 ');
assert.equal(resolve(pair,['50 ',50],51).selected.key,50);
assert.equal(compareOrders(pair,[[50,'50 '],['50 ',50]],51).unambiguous,false);
const color=[{key:50,weight:50},{key:30,weight:30},{key:15,weight:15},{key:5,weight:5}];
assert.equal(resolve(color,[50,30,15,5],96).selected.key,5);
assert.equal(resolve(color,[50,30,15,5],51).selected.key,30);
assert.throws(()=>resolve(color,[50,30,15,5],101),/range/);
assert.equal(resolve([{key:'x',weight:0},{key:3,weight:1}],['x',3],1).selected.key,3);
console.log('PASS: 14 assertions');
