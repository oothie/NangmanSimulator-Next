#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {preflight,PATHS}=require('./gate_table_order_preflight.cjs');
assert.equal(PATHS.size,6);
const tianyi=PATHS.get('천일교').map(({path,kind})=>({path,roll:kind==='three'?1:60}));
const x=preflight('천일교',tianyi);
assert.equal(x.sourceWeightedStageCount,8);
assert.equal(x.providedWeightedStageCount,8);
assert.deepEqual(x.missingWeightedStages,[]);
assert.deepEqual(x.ambiguousEffectPaths,[]);
assert.equal(x.allThreeModelEffectsAgreeForGivenStageRolls,true);
assert.equal(x.hasIndependentNativePairsProof,false);
assert.equal(x.hasIndependentNativeSeedProgressionProof,false);
assert.equal(x.exactGameGearForecastAllowed,false);
assert.equal(x.accountDataUsed,false);
const mixed=preflight('혈의루',PATHS.get('혈의루').map(x=>({path:x.path,roll:1})));
assert(mixed.ambiguousEffectPaths.length>0);
assert.equal(mixed.allThreeModelEffectsAgreeForGivenStageRolls,false);
const incomplete=preflight('천일교',[tianyi[0]]);
assert.equal(incomplete.providedWeightedStageCount,1);
assert.equal(incomplete.missingWeightedStages.length,7);
assert.equal(incomplete.allThreeModelEffectsAgreeForGivenStageRolls,false);
const jxz=preflight('취선채',PATHS.get('취선채').map(t=>({path:t.path,roll:1})));
assert.deepEqual(jxz.dynamicWeightedStages,['3/11/2/imp_no/2/2']);
assert.equal(jxz.allThreeModelEffectsAgreeForGivenStageRolls,false);
assert.throws(()=>preflight('미출시 관문',[]),/Unsupported/);
assert.throws(()=>preflight('천일교',[...tianyi,tianyi[0]]),/Duplicate/);
assert.throws(()=>preflight('천일교',[{path:'bad',roll:1}]),/Unrecognized/);
assert.throws(()=>preflight('천일교',[{path:tianyi[0].path,roll:0}]),/outside/);
assert(!JSON.stringify(x).includes('OnlyID'));
console.log('PASS three-model low-gate effect preflight, native-certification guard, dynamic and missing-stage refusal');
