#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {audit,possibleAttribution}=require('./after_save_equipment_evidence.cjs');
const keys={seed_jxz:11,seed_zjb:21,seed_33888:22,seed_xyl:31,seed_trm:41,seed_tyj:51,seed_kgm:61};
const wins={win_jxz:1,win_zjb:1,win_xyl:1,win_trm:1,win_tyj:1,win_kgm:1};
const equip=(only,id,color)=>({OnlyID:only,ID:id,Color:color});
const original={Rnds:{Sds:keys},globalVariable:wins,Equips:[equip(991111,4002,2)],PrivateInfo:'DO_NOT_ECHO'};
const after=structuredClone(original);
after.Rnds.Sds.seed_tyj=52;after.globalVariable.win_tyj=2;
after.Rnds.Sds.seed_kgm=62;after.globalVariable.win_kgm=2;
after.Equips.push(equip(991112,4808,3));
const x=audit(original,after);
assert.equal(x.gateProgress.filter(g=>g.consistency==='win-and-seed-moved').length,2);
assert.equal(x.newPossibleGateEquipment.length,1);
assert.equal(x.newPossibleGateEquipment[0].color,'청색');
assert.equal(x.newPossibleGateEquipment[0].identification,'ambiguous-among-progressed-gates');
assert.deepEqual(x.newPossibleGateEquipment[0].progressedGateCandidates.map(c=>c.gate),['천일교','고골문']);
assert.equal(x.strictNativeForwardValidation,false);
assert.equal(x.independentDropAttributionConfirmed,false);
assert.equal(x.completeInventoryContinuity,true);
assert(!JSON.stringify(x).includes('991111'));
assert(!JSON.stringify(x).includes('991112'));
assert(!JSON.stringify(x).includes('DO_NOT_ECHO'));
const one=structuredClone(after);one.globalVariable.win_kgm=1;one.Rnds.Sds.seed_kgm=61;
const y=audit(original,one);
assert.equal(y.newPossibleGateEquipment[0].identification,'one-compatible-gate-not-confirmed');
assert.equal(y.newPossibleGateEquipment[0].progressedGateCandidates[0].gate,'천일교');
const noProgress=structuredClone(original);noProgress.Equips.push(equip(1114,4808,2));
assert.equal(audit(original,noProgress).newPossibleGateEquipment[0].identification,'not-linked-to-observed-win');
const lost=structuredClone(after);lost.Equips=lost.Equips.filter(e=>e.OnlyID!==991111);
assert.equal(audit(original,lost).completeInventoryContinuity,false);
const mutated=structuredClone(after);mutated.Equips[0].Color=3;
assert.equal(audit(original,mutated).preexistingEquipmentChangedCount,1);
assert(possibleAttribution(4406).some(x=>x.gate==='혈의루'));
assert.deepEqual(possibleAttribution(799999),[]);
assert.throws(()=>audit({Rnds:{Sds:keys},globalVariable:wins,Equips:[{ID:4808,Color:3}]},after),/OnlyID/);
assert.throws(()=>audit(original,{...after,Equips:[equip(7,4808,2),equip(7,4407,3)]}),/Duplicate/);
assert.deepEqual(original,{Rnds:{Sds:keys},globalVariable:wins,Equips:[equip(991111,4002,2)],PrivateInfo:'DO_NOT_ECHO'});
console.log('PASS original six low-gate equipment pools, shared 80-tier attribution guard, delta privacy and no fake native pass');
