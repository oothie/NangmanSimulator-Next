#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {effect,atRoll,audit}=require('./audit_40_table_equipment_effects.cjs');
const a=audit();
assert.equal(a.tables,38);
assert.equal(a.rolls,3800);
assert.equal(a.stableEffectRolls,1240);
assert.deepEqual(a.effectMismatch,{firstVsLast:900,firstVsAbsent:2275,lastVsAbsent:2325});
assert.deepEqual(Object.keys(a.byGate),['취선채','추가성','혈의루','천일교','고골문','철인문']);
assert.equal(a.byGate['천일교'].stableEffectsAcrossAll,460);
assert.equal(a.byGate['철인문'].stableEffectsAcrossAll,60);
assert.equal(a.byGate['취선채'].stableEffectsAcrossAll,300);
assert.equal(a.nativeLuaJITPairsVerified,false);
assert.equal(a.futureItemDropGuaranteed,false);
assert.equal(a.individualSaveOrSeedUsed,false);
assert.equal(effect('천일교','3/4/2','number:10'),'no-drop');
assert.equal(effect('천일교','3/16/2','number:10'),'weapon');
assert.equal(effect('취선채','3/4/2','number:10'),'weapon');
assert.equal(effect('혈의루','3/7/2','string:50 '),'equipment');
assert.equal(effect('혈의루','3/7/2','number:50'),'no-drop');
const c=atRoll('천일교','3/4/2',41);
assert.equal(c.allModelEffectAgreement,false);
const d=atRoll('혈의루','3/7/2',1);
assert.equal(d.effects.first,'equipment');
assert.equal(d.effects.absent,'no-drop');
assert.equal(d.allModelEffectAgreement,false);
const ignored=atRoll('취선채','3/11/2/imp_no/2/2',1);
assert.equal(ignored.status,'dynamic-counter-unverified');
assert.equal(ignored.allModelEffectAgreement,false);
assert.throws(()=>atRoll('혈의루','3/7/2',0),/outside/);
assert.throws(()=>atRoll('혈의루','3/7/2',101),/outside/);
assert.throws(()=>effect('고골문','3/10/2','number:50 '),/Unexpected source/);
assert.throws(()=>atRoll('미출시 관문','1/2/3',1),/Unknown/);
console.log('PASS 38 source static tables, 1240/3800 three-way effect invariants and original Tianyi clear-vs-slot split');
