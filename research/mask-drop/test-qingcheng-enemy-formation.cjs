#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {FIRST,SECOND,THIRD,fromRolls,bossRoll,negBinomQuantile,forecastBanditHunts}=require('./qingcheng-enemy-formation.cjs');
assert.deepEqual(FIRST,[32950,32951,32952]);
assert.deepEqual(SECOND,[32951,32952,32953]);
assert.deepEqual(THIRD,[32951,32952,32953]);
const a=fromRolls({first:1,second:2,third:3});
assert.deepEqual(a.npcIds,[32950,32952,32953]);
assert.deepEqual(a.names,['산적','유적','탈영병']);
assert.equal(a.bandits,1);assert.equal(a.jhRandomCalls,3);
const b=fromRolls({first:3,second:1,boss:true});
assert.deepEqual(b.npcIds,[32952,32951,32954]);
assert.equal(b.bandits,0);assert.equal(b.jhRandomCalls,2);
assert.throws(()=>fromRolls({first:4,second:1,third:1}),RangeError);
assert.throws(()=>fromRolls({first:1,second:1,third:1,boss:true}),RangeError);
assert.equal(bossRoll({enabled:false}),false);
assert.equal(bossRoll({enabled:true,roll:260,food:0,bonus:250}),false);
assert.equal(bossRoll({enabled:true,roll:260,food:1,bonus:250}),true);
assert.throws(()=>bossRoll({enabled:true}),RangeError);
const evidence=require('./60014-qingcheng-enemy-formation-source.json');
assert.equal(evidence.jhConfig.prototype,20);
assert.equal(evidence.jhConfig.nativeAliasRandom.assignment,'math.jhrandom=math.random');
assert.equal(evidence.jhConfig.whaleRandomOverride.assignment,'math.random=JHCommonUtils.getWhaleRand closure');
assert.equal(evidence.jhConfig.serializedJHRandomGlobalStateProven,false);
assert.equal(evidence.exactFutureFormationRecoverableFromAidrop70,false);
const f=forecastBanditHunts(10);
assert.equal(f.sourceChancePerBattle,1/3);
assert.equal(f.expectedBattles,30);
assert.equal(f.medianBattles,29);
assert.deepEqual(f.percentile90,[19,44]);
assert.deepEqual(f.percentile95,[17,47]);
assert.equal(f.actualFutureBanditSchedule,null);
assert.equal(f.exact7209AwardConfirmed,false);
assert.equal(negBinomQuantile(1,.5),2);
console.log('PASS source three-slot Qingcheng roster, 1/3 bandit chance and exact negative-binomial quantiles');
