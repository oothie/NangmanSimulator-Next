#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {draw}=require('../dungeon-lab/mask-7209-conditional.cjs');
const {compare}=require('./compare-qingcheng-saves-mask.cjs');
const fake=(seed)=>({Rnds:{Sds:{aidrop70:seed,aidrop71:876543}},accountPrivate:'PRIVACY_CANARY'});
const initial=173827;
let after=initial;
for(let i=0;i<3;i++)after=draw(after,100).seed;
const report=compare(fake(initial),fake(after),{fieldBattles:8,maxDraws:50,horizon:150});
assert.equal(report.reportedFieldBattles,8);
assert.equal(report.progressionClassification,'unique-candidate');
assert.equal(report.uniqueProgression,3);
assert.equal(report.fieldBattleCountNotAssumedEqualToDrawCount,true);
assert.equal(report.afterSaveUsedDirectly,true);
assert.equal(report.nextCandidateAidrop70Draw,report.candidateDrawsFromAfterSave[0]);
assert.equal(report.precedingLevel70DrawsBeforeMask,report.nextCandidateAidrop70Draw-1);
assert.equal(report.actualMaskAwardVerified,false);
assert.equal(report.firstStageOnePercentVerified,false);
assert.equal(report.exactFieldEnemyAppearanceForecast,null);
assert.equal(report.rawSaveOrSeedReported,false);
assert(!JSON.stringify(report).includes('173827'));
assert(!JSON.stringify(report).includes('PRIVACY_CANARY'));
const zero=compare(fake(initial),fake(initial),{fieldBattles:2,maxDraws:25});
assert.equal(zero.uniqueProgression,0);
assert.equal(zero.progressionClassification,'unique-candidate');
assert.throws(()=>compare(fake(initial),fake(after),{}),/fieldBattles/);
assert.throws(()=>compare(fake(initial),fake(after),{fieldBattles:1,maxDraws:0}),/maxDraws/);
assert.throws(()=>compare(fake(initial),fake(after),{fieldBattles:1,hitSlot:101}),/hitSlot/);
assert.throws(()=>compare({Rnds:{Sds:{}}},fake(after),{fieldBattles:1}),/aidrop70/);
const tooShort=compare(fake(initial),fake(after),{fieldBattles:8,maxDraws:2});
assert.equal(tooShort.progressionClassification,'no-match-in-range');
assert.equal(tooShort.nextCandidateAidrop70Draw,report.nextCandidateAidrop70Draw);
assert.deepEqual(fake(initial).Rnds.Sds,{aidrop70:initial,aidrop71:876543});
console.log('PASS two-save field battle comparison, no guessed bandit counts, refreshed 1% candidate and zero private input leakage');
