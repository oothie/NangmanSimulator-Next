#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {draw,NPC}=require('../dungeon-lab/mask-7209-conditional.cjs');
const {evaluate}=require('./validate-weight-hypotheses.cjs');
const save=x=>({Rnds:{Sds:{aidrop70:x}}});
const a=173827,d=draw(a,100),b=d.seed,e=draw(b,100);
const mask={npc:NPC.mask,before:save(a),after:save(b),outcome:'mask'};
const bandit={npc:NPC.bandit,before:save(b),after:save(e.seed),outcome:'other'};
const positive={bound:100,calls:1,hitFrom:d.value,hitTo:d.value,rewardDraw:1};
const wrong={bound:100,calls:1,hitFrom:d.value===1?2:1,hitTo:d.value===1?2:1,rewardDraw:1};
const zero={bound:100,calls:0,hitFrom:1,hitTo:100,rewardDraw:1};
const res=evaluate([mask,bandit],[positive,wrong,zero]);
assert.equal(res.events,2);
assert.equal(res.modelsTested,3);
assert.equal(res.compatibleCandidates.length,1);
assert.equal(res.compatibleCandidates[0].positiveMaskChecks,1);
assert.equal(res.sourceBranchVerified,false);
assert.equal(res.sourcePoolVerified,false);
assert.equal(res.exactDropPredictionAllowed,false);
assert.equal(res.privateInputsReported,false);
assert(!JSON.stringify(res).includes(String(a)));
assert(!JSON.stringify(res).includes(String(b)));
const negative=evaluate([{...mask,outcome:'none'}],[positive,wrong]);
assert.equal(negative.compatibleCandidates.length,2,'absence is not a verified negative');
const absent=evaluate([{...mask,before:{Rnds:{Sds:{}}}}],[positive]);
assert.equal(absent.compatibleCandidates.length,0);
assert.throws(()=>evaluate([{...mask,npc:35125}],[positive]),/Supported NPC/);
assert.throws(()=>evaluate([{...bandit,outcome:'mask'}],[positive]),/bandit/);
assert.throws(()=>evaluate([mask],[{...positive,bound:0}]),/Explicit valid/);
assert.throws(()=>evaluate([],[positive]),/events/);
console.log('PASS hypothetical 7209 weight-state filter: positive evidence, negatives, missing lane, privacy');
