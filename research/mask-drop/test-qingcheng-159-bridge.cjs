#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {draw,NPC}=require('../dungeon-lab/mask-7209-conditional.cjs');
const {QINGCHENG,evaluate,assess159}=require('./qingcheng-159-bridge.cjs');
const fake={Rnds:{Sds:{aidrop70:173827}}};
assert.equal(QINGCHENG[32950].lane,'aidrop70');
assert.equal(QINGCHENG[32951].lane,'aidrop71');
assert.equal(QINGCHENG[32952].lane,'aidrop72');
assert.equal(QINGCHENG[32953].lane,'aidrop73');
assert.equal(QINGCHENG[32954].lane,'aidrop75');
const one=assess159(fake);
assert.equal(one.fieldFights,159);
assert.equal(one.countedLevel70BanditKills,159);
assert.equal(one.countedAidrop70CallsBeforeMask,159);
assert.equal(one.maskFirstStageIndex,160);
assert.equal(one.exactRewardProven,false);
assert.equal(one.privateInputReported,false);
assert(!JSON.stringify(one).includes('173827'));
let s=173827;
for(let i=0;i<159;i++)s=draw(s,100).seed;
assert.equal(one.maskFirstStageFavorable,draw(s,100).value===1);
const mixed=evaluate(fake,{fights:[[32950,32951],[32952,32953],[32954],[32950,32954]]});
assert.equal(mixed.fieldFights,4);
assert.equal(mixed.countedLevel70BanditKills,2);
assert.equal(mixed.countedAidrop70CallsBeforeMask,2);
assert.equal(mixed.maskFirstStageIndex,3);
const double=evaluate(fake,{fights:[[32950,32950],[32951]]});
assert.equal(double.maskFirstStageIndex,3);
assert.equal(double.fieldFights,2);
assert.throws(()=>evaluate(fake,{fights:[[35125]]}),/32950-32954/);
assert.throws(()=>evaluate(fake,{fights:[[NPC.mask]]}),/32950-32954/);
assert.throws(()=>evaluate(fake,{fights:[[32950]],maskNpc:35125}),/30681/);
assert.throws(()=>evaluate({Rnds:{Sds:{}}},{fights:[[32950]]}),/aidrop70/);
assert.deepEqual(fake,{Rnds:{Sds:{aidrop70:173827}}});
console.log('PASS 159 Qingcheng battle vs aidrop70-call separation and private-safe Manhogang candidate');
