#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {draw}=require('../dungeon-lab/mask-7209-conditional.cjs');
const {audit,progress}=require('./qingcheng-appearance-from-saves.cjs');
const copy=(x)=>JSON.parse(JSON.stringify(x));
const initial={Rnds:{Sds:{aidrop70:173827,aidrop71:31245,aidrop72:31457,aidrop73:31567,aidrop75:32961}},Secret:'private'};
const afterOne=copy(initial);
afterOne.Rnds.Sds.aidrop71=draw(initial.Rnds.Sds.aidrop71,100).seed;
const afterTwo=copy(afterOne);
afterTwo.Rnds.Sds.aidrop70=draw(initial.Rnds.Sds.aidrop70,100).seed;
afterTwo.Rnds.Sds.aidrop71=draw(afterOne.Rnds.Sds.aidrop71,100).seed;
afterTwo.Rnds.Sds.aidrop72=draw(initial.Rnds.Sds.aidrop72,100).seed;
const result=audit([initial,afterOne,afterTwo]);
assert.equal(result.battleIntervals,2);
assert.equal(result.rows[0].level70DrawCount,0);
assert.equal(result.rows[1].level70DrawCount,1);
assert.equal(result.inferredLevel70Calls,1);
assert.equal(result.futureAppearanceSchedule,null);
assert.equal(result.originalGameFormationRoutineRecovered,false);
assert.equal(result.privateInputsReported,false);
assert.deepEqual(result.rows[0].level71CandidateCallCounts,[1]);
assert.deepEqual(result.rows[1].level71CandidateCallCounts,[1]);
assert.deepEqual(result.rows[1].level72CandidateCallCounts,[1]);
assert(!JSON.stringify(result).includes('173827'));
assert(!JSON.stringify(result).includes('private'));
const invalid=audit([{},afterOne]);
assert.equal(invalid.rows[0].level70DrawCount,null);
assert.equal(invalid.inferredLevel70Calls,null);
assert.deepEqual(progress(173827,173827,{maxDraws:6}).matches,[0]);
assert.throws(()=>audit([initial]),/consecutive/);
console.log('PASS source-model per-battle [0,1] 70-level transition reconstruction and privacy');
