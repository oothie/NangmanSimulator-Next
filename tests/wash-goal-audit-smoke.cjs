// Goal coverage is a read-only inventory of exact native WASM talent slots.
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),ctx={window:{}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'engine/wash-goal-audit.js'),'utf8'),ctx);
const api=ctx.window.NangmanWashGoal,valid=[248,249,250,271,272,268];
const goals=Array.from(api.parsePairs('271:249\n272:248\n250:268',valid));
assert.equal(goals.length,3);
assert.equal(goals[0].purpleId,271);
assert.equal(goals[2].conflictId,268);
assert.throws(()=>api.parsePairs('271:249\n271:248',valid),/중복/);
assert.throws(()=>api.parsePairs('271:999',valid),/원본 자색/);
assert.throws(()=>api.parsePairs('bad-pair',valid),/형식/);
const before=[{id:271,locked:true},{id:250,locked:false},{id:248,locked:false},{id:269,locked:false}];
const after=[{id:271,locked:true},{id:250,locked:false},{id:272,locked:true},{id:269,locked:false}];
const original=JSON.stringify([before,after]);
const baseline=api.evaluate(before,goals);
assert.equal(baseline.found,2);
assert.equal(baseline.locked,1);
assert.equal(baseline.complete,false);
assert.deepEqual(Array.from(baseline.missing),[272]);
const progress=api.progression(before,after,goals);
assert.equal(progress.preserved,true);
assert.deepEqual(Array.from(progress.gained),[272]);
assert.equal(progress.after.complete,true);
const removed=[{id:250,locked:false},{id:248,locked:false},{id:272,locked:false},{id:269,locked:false}];
const lost=api.progression(before,removed,goals);
assert.equal(lost.preserved,false);
assert.deepEqual(Array.from(lost.lost),[271]);
assert.equal(JSON.stringify([before,after]),original,'source WASM talent snapshots stay unchanged');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.includes('./engine/wash-goal-audit.js'));
assert(html.includes('NangmanWashGoal.evaluate('));
assert(html.includes('현재 모의 WASM의 목표 자맥 보유 현황'));
assert(html.includes('output.goalsComplete'));
console.log('PASS: real-slot-only target coverage, lock flags, goal loss/gain and no false 4-target completion');
